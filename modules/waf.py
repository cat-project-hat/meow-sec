WAF_PROBES = [
    ("SQLi basic",    "/?id=1'"),
    ("XSS basic",     "/?q=<script>alert(1)</script>"),
    ("SQLi union",    "/?id=1 UNION SELECT 1,2,3--"),
    ("Path traversal","/../../../etc/passwd"),
    ("Null byte",     "/?file=../etc/passwd%00"),
    ("LFI php",       "/?page=php://filter/convert.base64-encode/resource=index"),
    ("CMDi basic",    "/?cmd=;id"),
    ("XSS svg",       "/?x=<svg/onload=alert(1)>"),
]

NORMAL_HEADERS = {
    "User-Agent":      "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/124.0 Safari/537.36",
    "Accept":          "text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8",
    "Accept-Language": "en-US,en;q=0.5",
    "Connection":      "keep-alive",
}

# ─── DETECTION ENGINE ────────────────────────────────────────

def _normalize_url(target: str) -> str:
    if "://" not in target:
        target = "https://" + target
    return target.rstrip("/")

def detect_waf(target: str, probe: bool = True) -> dict:
    """Retourne dict: {waf_name: score, ...} et les détails de détection"""
    url  = _normalize_url(target)
    results = {}
    raw_headers = {}
    raw_cookies = {}
    body_lower  = ""
    status      = 0

    # 1. Requête normale
    try:
        r = requests.get(url, headers=NORMAL_HEADERS, timeout=12,
                         allow_redirects=True, verify=False, proxies=_px())
        status      = r.status_code
        raw_headers = {k.lower(): v.lower() for k, v in r.headers.items()}
        raw_cookies = {k.lower(): v.lower() for k, v in r.cookies.items()}
        body_lower  = r.text.lower()[:8000]
    except Exception as e:
        return {"error": str(e)}

    # 2. Scoring par signature
    for waf_name, sig in WAF_DB.items():
        score   = 0
        matched = []

        for h in sig["headers"]:
            if h in raw_headers:
                score += 25
                matched.append(f"header:{h}")

        srv = raw_headers.get("server", "")
        for s in sig["server"]:
            if s in srv:
                score += 20
                matched.append(f"server:{s}")

        for c in sig["cookies"]:
            if any(c.lower() in k for k in raw_cookies):
                score += 20
                matched.append(f"cookie:{c}")

        for b in sig["body"]:
            if b in body_lower:
                score += 15
                matched.append(f"body:{b[:30]}")

        if status in sig["codes"] and sig["codes"]:
            score += 5

        if score > 0:
            results[waf_name] = {"score": score, "matched": matched,
                                 "color": sig["color"],
                                 "bypass": sig["bypass"]}

    # 3. Probes WAF (envoie des payloads)
    if probe and results:
        probe_results = []
        for probe_name, probe_path in WAF_PROBES[:4]:
            try:
                r2 = requests.get(url + probe_path, headers=NORMAL_HEADERS, timeout=10,
                                  timeout=8, allow_redirects=False, verify=False, proxies=_px())
                probe_results.append((probe_name, r2.status_code, probe_path))
                time.sleep(0.3)
            except Exception:
                probe_results.append((probe_name, 0, probe_path))
        return {"waf": results, "status": status,
                "server": raw_headers.get("server","?"),
                "probes": probe_results,
                "headers_seen": dict(list(raw_headers.items())[:12])}

    return {"waf": results, "status": status,
            "server": raw_headers.get("server","?"),
            "probes": [], "headers_seen": dict(list(raw_headers.items())[:12])}

# ─── DISPLAY ─────────────────────────────────────────────────

def _display_results(target: str, data: dict):
    if "error" in data:
        err(f"Request failed: {data['error']}"); return

    console.print()
    info(f"Target: [{CY}]{target}[/]  HTTP: [{G1}]{data['status']}[/]  "
         f"Server: [{OR}]{data['server']}[/]")
    console.print()

    waf = data.get("waf", {})
    if not waf:
        ok("No WAF/CDN signatures detected — target may be unprotected or use custom WAF")
    else:
        # Trier par score
        sorted_waf = sorted(waf.items(), key=lambda x: x[1]["score"], reverse=True)
        top_name, top_data = sorted_waf[0]

        if top_data["score"] >= 40:
            find(f"WAF detected: [{top_data['color']}]{top_name}[/]  "
                 f"(confidence: [{G1}]{min(top_data['score'],100)}%[/])")
        else:
            warn(f"Possible WAF: [{top_data['color']}]{top_name}[/]  "
                 f"(confidence: [{OR}]{top_data['score']}%[/])")

        # Table des résultats
        t = Table(box=box.SIMPLE, header_style=CY, border_style=G2,
                  show_edge=False, show_lines=False)
        t.add_column("WAF / CDN",   style=f"bold {G1}", width=25)
        t.add_column("Confidence",  style=CY, width=12)
        t.add_column("Evidence",    style=DM)

        for name, d in sorted_waf:
            conf = min(d["score"], 100)
            c = G1 if conf >= 60 else (OR if conf >= 30 else DM)
            matched_str = ", ".join(d["matched"][:4])
            t.add_row(name, f"[{c}]{conf}%[/]", matched_str)
        console.print(t)

        # Bypass hints
        console.print()
        console.print(Panel(
            "\n".join(f"  [{G1}]▸[/] {h}" for h in top_data["bypass"]),
            title=f"[{OR}]◈ Bypass hints for {top_name} ◈",
            border_style=OR
        ))

    # Probes
    if data.get("probes"):
        console.print()
        probe_rows = []
        for name, code, path in data["probes"]:
            c = G1 if code == 200 else (OR if code in (301,302) else RD)
            probe_rows.append((name, f"[{c}]{code}[/]", path))
        print_result_table("WAF Probe Results", ["Probe","Status","Path"], probe_rows)

    # Headers
    console.print()
    t2 = Table(box=box.SIMPLE, header_style=CY, border_style=G2, show_edge=False)
    t2.add_column("Header",  style=CY, width=30)
    t2.add_column("Value",   style=DM)
    for k, v in data.get("headers_seen", {}).items():
        t2.add_row(k, v[:80])
    console.print(t2)

def _save(target: str, data: dict):
    os.makedirs("data", exist_ok=True)
    fname = f"data/waf_{target.replace('https://','').replace('http://','').replace('/','_')}_{datetime.now().strftime('%Y%m%d_%H%M%S')}.json"
    with open(fname, "w", encoding="utf-8") as f:
        import json
        d = {"target": target, **data}
        d["waf"] = {k: {**v, "color": str(v.get("color",""))} for k,v in d.get("waf",{}).items()}
        json.dump(d, f, indent=2)
    ok(f"Saved: {fname}")

