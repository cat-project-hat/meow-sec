def run():
    show_module_banner("waf")
    cat_talk(CAT_SCAN, "WAF fingerprinting engine loaded.", OR)
    console.print()

    if not HAS_REQUESTS:
        err("requests library required."); return

    while True:
        console.print(f"  [{G1}][1][/] WAF / CDN detect  (single target)")
        console.print(f"  [{G1}][2][/] Batch scan  (list of URLs)")
        console.print(f"  [{G1}][0][/] Back")
        console.print()
        choice = ask_choice("WAF", "0")

        if choice == "0": break

        elif choice == "1":
            console.print(Rule(f"[{G1}] WAF FINGERPRINT ", style=G2))
            target = Prompt.ask(f"  [{G1}]◈ Target (URL / domain)[/]").strip()
            if not target: continue
            probe  = Confirm.ask(f"  [{OR}]◈ Send probe payloads (noisy)?[/]", default=True)
            console.print()
            with Progress(SpinnerColumn(style=G1),
                          TextColumn(f"[{G1}]Fingerprinting {{task.description}}"),
                          TimeElapsedColumn(), console=console) as p:
                t = p.add_task(target, total=None)
                data = detect_waf(target, probe)
            _display_results(target, data)
            _save(target, data)

        elif choice == "2":
            path = Prompt.ask(f"  [{G1}]◈ File with URLs (one per line)[/]").strip()
            if not os.path.exists(path):
                err(f"File not found: {path}"); continue
            urls = [l.strip() for l in open(path, encoding="utf-8") if l.strip()]
            info(f"Scanning {len(urls)} targets...")
            for u in urls:
                console.print(f"\n  [{G2}]──────── {u} ────────[/]")
                data = detect_waf(u, probe=False)
                waf  = data.get("waf", {})
                if waf:
                    top = max(waf, key=lambda x: waf[x]["score"])
                    find(f"{u} → [{OR}]{top}[/]  ({min(waf[top]['score'],100)}%)")
                else:
                    ok(f"{u} → No WAF detected")
        console.print()

